// ========================================
// GET CURRENT LANGUAGE
// ========================================

function getLanguage() {

    const savedLanguage =
        localStorage.getItem("language");

    if (
        savedLanguage &&
        translations[savedLanguage]
    ) {

        return savedLanguage;

    }

    return "gu";

}


// ========================================
// APPLY LANGUAGE
// ========================================

function applyLanguage(language) {

    if (!translations[language]) {

        language = "gu";

    }


    const dictionary =
        translations[language];


    console.log(
        "Applying language:",
        language
    );


    // ====================================
    // NORMAL TEXT
    // ====================================

    document
        .querySelectorAll("[data-i18n]")
        .forEach((element) => {

            const key =
                element.dataset.i18n;


            if (
                dictionary[key] !== undefined
            ) {

                element.textContent =
                    dictionary[key];

            }

        });


    // ====================================
    // PLACEHOLDERS
    // ====================================

    document
        .querySelectorAll(
            "[data-i18n-placeholder]"
        )
        .forEach((element) => {

            const key =
                element.dataset.i18nPlaceholder;


            if (
                dictionary[key] !== undefined
            ) {

                element.placeholder =
                    dictionary[key];

            }

        });


    // ====================================
    // PAGE TITLE
    // ====================================

    document
        .querySelectorAll(
            "[data-i18n-title]"
        )
        .forEach((element) => {

            const key =
                element.dataset.i18nTitle;


            if (
                dictionary[key] !== undefined
            ) {

                document.title =
                    dictionary[key];

            }

        });


    // ====================================
    // META CONTENT
    // ====================================

    document
        .querySelectorAll(
            "[data-i18n-content]"
        )
        .forEach((element) => {

            const key =
                element.dataset.i18nContent;


            if (
                dictionary[key] !== undefined
            ) {

                element.setAttribute(
                    "content",
                    dictionary[key]
                );

            }

        });


    // ====================================
    // HTML LANGUAGE
    // ====================================

    document.documentElement.lang =
        language;


    // ====================================
    // SAVE
    // ====================================

    localStorage.setItem(
        "language",
        language
    );


    // ====================================
    // ACTIVE LANGUAGE BUTTON
    // ====================================

    document
        .querySelectorAll(
            "[data-language]"
        )
        .forEach((button) => {

            button.classList.toggle(
                "active",
                button.dataset.language === language
            );

        });

}


// ========================================
// LANGUAGE BUTTONS
// ========================================

document.addEventListener(
    "click",
    (event) => {

        const button =
            event.target.closest(
                "[data-language]"
            );


        if (!button) {

            return;

        }


        const language =
            button.dataset.language;


        if (
            !translations[language]
        ) {

            return;

        }


        applyLanguage(
            language
        );

    }
);


// ========================================
// INITIALIZE
// ========================================

document.addEventListener(
    "DOMContentLoaded",
    () => {

        applyLanguage(
            getLanguage()
        );

    }
);